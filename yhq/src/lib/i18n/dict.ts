export const DICTS: Record<"uz" | "ru", Record<DictKey, string>> = { uz, ru };

export function interpolate(s: string, vars?: Record<string, string | number>) {
  if (!vars) return s;
  return s.replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? `{${k}}`));
}

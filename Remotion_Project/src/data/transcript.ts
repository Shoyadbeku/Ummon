// Split long lines into subtitle cues (max ~64 chars), timed proportionally by character count.
export type Cue = {start: number; end: number; text: string};
export const toCues = (lines: Line[], maxChars = 64): Cue[] => {
	const cues: Cue[] = [];
	for (const l of lines) {
		const words = l.text.split(' ');
		const chunks: string[] = [];
		let cur = '';
		for (const w of words) {
			if ((cur + ' ' + w).trim().length > maxChars && cur) {
				chunks.push(cur.trim());
				cur = w;
			} else cur = (cur + ' ' + w).trim();
		}
		if (cur) chunks.push(cur);
		// Balance: avoid tiny last chunk
		if (chunks.length > 1 && chunks[chunks.length - 1].length < 14) {
			const last = chunks.pop()!;
			chunks[chunks.length - 1] += ' ' + last;
		}
		const total = chunks.reduce((a, c) => a + c.length, 0);
		let t = l.start;
		for (const c of chunks) {
			const d = ((l.end - l.start) * c.length) / total;
			cues.push({start: t, end: t + d, text: c});
			t += d;
		}
	}
	return cues;
};


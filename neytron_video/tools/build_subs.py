"""Build word-timed subtitle cues from Whisper output + corrected Uzbek text.

Usage: python3 build_subs.py whisper.json transcript_uz.txt subtitles.ts Subtitles.srt
Each corrected line corresponds to one Whisper segment; corrected words are spread over
that segment's spoken span, weighted by length, so timing follows the original voice.
"""
import json, re, sys

segs = json.load(open(sys.argv[1]))
lines = [l.rstrip("\n") for l in open(sys.argv[2], encoding="utf-8")]
assert len(segs) == len(lines), (len(segs), len(lines))

words = []
for s, line in zip(segs, lines):
    ws = line.split()
    if not ws:
        continue
    a = s["words"][0]["s"] if s["words"] else s["start"]
    b = s["words"][-1]["e"] if s["words"] else s["end"]
    weights = [len(w) + 2 for w in ws]
    tot = sum(weights)
    t = a
    for w, wt in zip(ws, weights):
        d = (b - a) * wt / tot
        words.append({"t": w, "s": round(t, 3), "e": round(t + d, 3)})
        t += d

cues = []
cur = []
for i, w in enumerate(words):
    cur.append(w)
    nxt = words[i + 1] if i + 1 < len(words) else None
    end_punct = re.search(r"[.?!]$", w["t"])
    soft = re.search(r"[,:;—]$", w["t"])
    gap = (nxt["s"] - w["e"]) if nxt else 9
    dur = w["e"] - cur[0]["s"]
    in_name = w['t'] in ('Kim', 'Chen', 'Doan', 'Thi', 'Siti', 'Chan', 'Son')
    # never break a cue inside a personal name ("Kim Chen | In")
    long_cue = len(cur) >= 8 or dur > 4.2
    if nxt is None or end_punct or (soft and len(cur) >= 4) or (not in_name and (gap > 0.45 or long_cue)) or gap > 1.2:
        cues.append(cur)
        cur = []

out = []
for i, c in enumerate(cues):
    s = c[0]["s"]
    e = c[-1]["e"] + 0.25
    if i + 1 < len(cues):
        e = min(e, cues[i + 1][0]["s"] - 0.02)
    out.append({"s": round(s, 3), "e": round(e, 3), "w": c})

with open(sys.argv[3], "w", encoding="utf-8") as f:
    f.write("// Generated by tools/build_subs.py — subtitle cues synced to the original narration.\n")
    f.write("export type Cue = {s: number; e: number; w: {t: string; s: number; e: number}[]};\n")
    f.write("export const CUES: Cue[] = " + json.dumps(out, ensure_ascii=False) + ";\n")


def ts(x):
    h = int(x // 3600)
    m = int(x % 3600 // 60)
    s = x % 60
    return f"{h:02d}:{m:02d}:{int(s):02d},{int(round((s - int(s)) * 1000)):03d}"


off = float(sys.argv[5]) if len(sys.argv) > 5 else 0.0
with open(sys.argv[4], "w", encoding="utf-8") as f:
    for i, c in enumerate(out, 1):
        f.write(f"{i}\n{ts(c['s'] + off)} --> {ts(c['e'] + off)}\n{' '.join(w['t'] for w in c['w'])}\n\n")
print(len(words), "words", len(out), "cues")
